function routineApplicant(index: number): Applicant {
  const n = index + 1;
  const grade = GRADES[index % GRADES.length];
  const school = ROUTINE_SCHOOLS[index % ROUTINE_SCHOOLS.length];
  const first = FIRST[index % FIRST.length];
  const last = LAST[(index * 3) % LAST.length];
  return base({
    id: idOf(n),
    name: `${first} ${last}`,
    grade: grade.name,
    age: grade.age,
    language: index % 7 === 0 ? "English" : index % 7 === 1 ? "French" : "English",
    second_language: index % 5 === 0 ? "Spanish" : index % 5 === 1 ? "Mandarin" : "French",
    prior_school: school.name,
    prior_school_country: school.country,
    extracurricular: ROUTINE_ACTIVITIES[index % ROUTINE_ACTIVITIES.length],
    reason_for_applying: ROUTINE_REASONS[index % ROUTINE_REASONS.length],
    siblings_information: index % 11 === 0 ? "none" : null,
    tags: ["routine"],
  });
}

function buildApplicants(): Applicant[] {
  const byId = new Map<string, Applicant>();
  for (const planted of PLANTED) byId.set(planted.id, planted);
  const all: Applicant[] = [];
  for (let i = 0; i < BATCH_SIZE; i += 1) {
    const id = idOf(i + 1);
    all.push(byId.get(id) ?? routineApplicant(i));
  }
  return all;
}

