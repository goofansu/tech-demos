function idOf(n: number): string {
  return `A-${String(n).padStart(4, "0")}`;
}

type ApplicantDraft = Omit<
  Applicant,
  "application_status" | "deadline" | "competing_offer" | "scholarship" | "officer_notes" | "tags"
> &
  Partial<Pick<Applicant, "application_status" | "deadline" | "competing_offer" | "scholarship" | "officer_notes" | "tags">>;

function base(partial: ApplicantDraft): Applicant {
  const {
    application_status = "active",
    deadline = null,
    competing_offer = null,
    scholarship = null,
    officer_notes = null,
    tags = [],
    ...rest
  } = partial;
  return { application_status, deadline, competing_offer, scholarship, officer_notes, tags, ...rest };
}

